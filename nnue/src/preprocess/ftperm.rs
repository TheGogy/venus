use crate::arch::{EmbedNNUEData, FT_PSQT_ROWS, FT_THRT_ROWS, L1_LEN, PAIRWISE_LEN};

/// Apply [`FTPERM_INDICES`] to one feature transform row in place.
fn permute_row<T: Copy>(row: &mut [T], buf: &mut [T; L1_LEN]) {
    buf.copy_from_slice(&row[..L1_LEN]);

    for (ix, iy) in FTPERM_INDICES.iter().copied().enumerate() {
        row[ix] = buf[iy];
        row[ix + PAIRWISE_LEN] = buf[iy + PAIRWISE_LEN];
    }
}

impl EmbedNNUEData {
    /// Permute the features to maximize pairwise activations within each block.
    pub fn ftperm(&mut self) {
        if !USE_FTPERM {
            return;
        }

        let mut buf_i16 = [0i16; L1_LEN];
        for feat in 0..FT_PSQT_ROWS {
            permute_row(&mut self.ftw_psqt[feat * L1_LEN..(feat + 1) * L1_LEN], &mut buf_i16);
        }

        let mut buf_i8 = [0i8; L1_LEN];
        for feat in 0..FT_THRT_ROWS {
            permute_row(&mut self.ftw_thrt[feat * L1_LEN..(feat + 1) * L1_LEN], &mut buf_i8);
        }

        permute_row(&mut self.ftb, &mut buf_i16);

        let l1w_unperm = self.l1w;
        for (ix, iy) in FTPERM_INDICES.iter().copied().enumerate() {
            self.l1w[ix] = l1w_unperm[iy];
            self.l1w[ix + PAIRWISE_LEN] = l1w_unperm[iy + PAIRWISE_LEN];
        }
    }
}

